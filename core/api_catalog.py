"""Every HTTP endpoint the OneNess TOR API exposes — declared once.

This registry is the single source of truth behind four surfaces:

1. ``GET /api/docs`` and the ``/docs`` page (endpoint browser + live "Try it"),
2. the dynamic forms on every page (fields are generated from ``params``),
3. the **Ollama system prompt** — :func:`prompt_text` is injected verbatim so
   the model knows the real API before it answers a single word,
4. the **fetch-data tool** (``core/tools.py``), which resolves a name here and
   performs the real HTTP request.

A test walks the Flask url map and fails if this registry and the routes drift,
so the model can never be told about an endpoint that does not exist.

Param dicts: ``{"name", "in": path|query|json, "type": string|int|float|bool|object,
"required", "description", "example", "enum"}``.
"""
