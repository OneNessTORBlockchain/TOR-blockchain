def P(name: str, *, where: str = "query", type: str = "string",
      required: bool = False, description: str = "",
      example: Any = None, enum: list[str] | None = None) -> dict:
    """One parameter of an endpoint."""
    param = {"name": name, "in": where, "type": type, "required": required,
             "description": description}
    if example is not None:
        param["example"] = example
    if enum:
        param["enum"] = list(enum)
    return param


def E(name: str, method: str, path: str, summary: str, *,
      params: tuple = (), auth: str = "public", cost: float = 0.0,
      returns: str = "") -> dict:
    """One endpoint."""
    return {"name": name, "group": name.split(".")[0], "method": method.upper(),
            "path": path, "summary": summary, "params": list(params),
            "auth": auth, "cost_tor": float(cost), "returns": returns}


