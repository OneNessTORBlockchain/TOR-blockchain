def prompt_text(base_url: str = "", *, include_bodies: bool = True) -> str:
    """The API section of the Ollama system prompt (stable, deterministic)."""
    lines = [f"LIVE ONENESS TOR API — {len(ALL)} endpoints at {base_url or 'the node'}",
             'Every response is the envelope {"ok": bool, "data": ..., "error": null}.',
             "Call fetch_oneness_data{endpoint, params} — never guess a number.",
             "Amounts are microTOR on the chain (1 TOR = 100000000 microTOR); "
             "convert to TOR for humans.",
             "Paid actions are charged in TOR on-chain: " +
             ", ".join(f"{e['name']} {e['cost_tor']:g}" for e in ALL if e["cost_tor"]),
             ""]
    for group in groups():
        lines.append(f"[{group['name']}] {group['description']}")
        for entry in ALL:
            if entry["group"] != group["name"]:
                continue
            signature = _param_signature(entry)
            query = f"?{signature}" if signature and entry["method"] == "GET" else ""
            cost = f" cost={entry['cost_tor']:g}TOR" if entry["cost_tor"] else ""
            lines.append(f"- {entry['name']} | {entry['method']} {entry['path']}{query}"
                         f" | {entry['auth']}{cost} | {entry['summary']}"
                         f" -> {entry['returns']}")
            if include_bodies and entry["params"]:
                body = ", ".join(
                    f"{p['name']}:{p['type']}{'*' if p['required'] else '?'}"
                    for p in entry["params"] if p["in"] in ("json", "path"))
                if body and entry["method"] != "GET":
                    lines.append(f"    body: {body}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def openapi(base_url: str = "/") -> dict:
    """Minimal OpenAPI 3.1 document generated from the registry."""
    paths: dict[str, dict] = {}
    for entry in ALL:
        operation: dict[str, Any] = {
            "operationId": entry["name"].replace(".", "_"),
            "summary": entry["summary"],
            "tags": [entry["group"]],
            "responses": {"200": {"description": "envelope {ok, data, error}"}},
        }
        parameters, body = [], {}
        for param in entry["params"]:
            schema = {"type": {"int": "integer", "float": "number",
                               "bool": "boolean", "object": "object"}.get(
                                   param["type"], "string")}
            if param.get("enum"):
                schema["enum"] = param["enum"]
            if param["in"] == "query":
                parameters.append({"name": param["name"], "in": "query",
                                   "required": param["required"], "schema": schema})
            elif param["in"] == "path":
                parameters.append({"name": param["name"], "in": "path",
                                   "required": True, "schema": schema})
            else:
                body[param["name"]] = schema
        if parameters:
            operation["parameters"] = parameters
        if body:
            operation["requestBody"] = {"content": {"application/json": {
                "schema": {"type": "object", "properties": body}}}}
        if entry["auth"] == "admin":
            operation["security"] = [{"AdminToken": []}]
        elif entry["auth"] == "api-key":
            operation["security"] = [{"ApiKey": []}]
        elif entry["auth"] == "wallet-session":
            operation["security"] = [{"WalletSession": []}]
        paths.setdefault(entry["path"], {})[entry["method"].lower()] = operation
    return {"openapi": "3.1.0",
            "info": {"title": "OneNess TOR API", "version": CATALOG_VERSION,
                     "description": "Every endpoint the node, the pages and the "
                                    "Ollama command brain share."},
            "servers": [{"url": base_url.rstrip("/") or "http://127.0.0.1:8090"}],
            "components": {"securitySchemes": {
                "AdminToken": {"type": "apiKey", "in": "header",
                               "name": "x-admin-token"},
                "WalletSession": {"type": "apiKey", "in": "header",
                                  "name": "x-wallet-session"},
                "ApiKey": {"type": "apiKey", "in": "header", "name": "x-api-key"}}},
            "paths": paths}


