_BY_NAME: dict[str, dict] = {entry["name"]: entry for entry in ALL}


def endpoints() -> list[dict]:
    """Every endpoint (defensive copies, so callers can't mutate the registry)."""
    return [{**entry, "params": [dict(param) for param in entry["params"]]}
            for entry in ALL]


def names() -> list[str]:
    return [entry["name"] for entry in ALL]


def by_name(name: str) -> dict | None:
    entry = _BY_NAME.get(str(name or "").strip())
    return {**entry, "params": [dict(p) for p in entry["params"]]} if entry else None


def groups() -> list[dict]:
    counts: dict[str, int] = {}
    for entry in ALL:
        counts[entry["group"]] = counts.get(entry["group"], 0) + 1
    order = [name for name in GROUPS if name in counts]
    order += [name for name in counts if name not in GROUPS]
    return [{"name": name, "description": GROUPS.get(name, ""),
             "count": counts[name]} for name in order]


def catalog_document(base_url: str = "") -> dict:
    return {"version": CATALOG_VERSION, "base_url": base_url,
            "count": len(ALL), "groups": groups(), "endpoints": endpoints(),
            "envelope": {"ok": True, "data": {}, "error": None},
            "auth_header": "x-admin-token",
            "auth_headers": {"admin": "x-admin-token", "wallet": "x-wallet-session",
                             "developer": "x-api-key"}}


def _param_signature(entry: dict) -> str:
    bits = []
    for param in entry["params"]:
        if param["in"] == "json":
            continue  # the body schema is listed on its own line
        marker = "*" if param["required"] else "?"
        example = param.get("example")
        suffix = "" if example is None else f"={example}"
        bits.append(f"{param['name']}:{param['type']}{marker}{suffix}")
    return ", ".join(bits)


