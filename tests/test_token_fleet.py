def test_a_re_mint_mints_new_wallets_and_freezes_the_old_generation(make_wallet, minted, node):
    """`start=121` is the re-mint: the same tickers, 120 brand-new key pairs."""
    first = token_fleet.run(majors=1, memes=1, dry_run=False)
    assert [entry["wallet"]["name"] for entry in first["created"]] == ["fleet001", "fleet002"]
    assert [entry["wallet_index"] for entry in first["created"]] == [1, 2]
    assert first["manifest"]["generation"] == 1
    assert first["manifest"]["superseded"] == []

    # a ticker is minted once per chain: a re-mint happens on a chain where the
    # tickers are free again (fresh genesis), which is why the wallets must be new
    node.setattr(token_fleet.meme, "chain_tokens", lambda: {})
    second = token_fleet.run(majors=1, memes=1, start=121, dry_run=False)
    assert [entry["wallet"]["name"] for entry in second["created"]] == ["fleet121", "fleet122"]
    assert [entry["wallet_index"] for entry in second["created"]] == [121, 122]
    assert second["manifest"]["generation"] == 2

    frozen = second["manifest"]["superseded"]
    assert frozen[0]["generation"] == 1 and frozen[0]["replaced"] == 2
    assert frozen[0]["store"].replace("\\", "/").endswith("token-fleet/gen-01.json")
    assert token_fleet._archive_path(1).is_file()

    stored = json.loads(token_fleet._manifest_path().read_text(encoding="utf-8"))
    assert stored["generation"] == 2
    assert [entry["wallet"]["name"] for entry in stored["entries"]] == ["fleet121", "fleet122"]
    archived = json.loads(token_fleet._archive_path(1).read_text(encoding="utf-8"))
    assert archived["entries"][0]["wallet"]["name"] == "fleet001"
    assert archived["entries"][0]["supply"] == 20_000_000


