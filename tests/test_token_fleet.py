def test_resuming_the_same_generation_merges_without_bumping_it(make_wallet, minted, node):
    """A retry of a run that lost one asset may only add that asset."""
    token_fleet.run(majors=1, memes=1, start=121, dry_run=False)
    assert token_fleet.manifest()["generation"] == 1
    assert token_fleet.manifest()["start"] == 121

    node.setattr(token_fleet.meme, "chain_tokens",
                 lambda: {"BTC": {"symbol": "BTC", "owner": "TOR1x"}})
    again = token_fleet.run(majors=1, memes=1, start=121, dry_run=False)
    assert [entry["symbol"] for entry in again["created"]] == ["BONK"]
    assert again["manifest"]["generation"] == 1
    assert again["manifest"]["count"] == 2
    assert [entry["wallet"]["name"] for entry in token_fleet.manifest()["entries"]] == \
        ["fleet121", "fleet122"]


