def test_a_failure_is_reported_per_token_and_the_run_continues(make_wallet, node):
    def create(**kwargs):
        if kwargs["symbol"] == "BTC":
            raise FeeError("fleet001 holds 0 TOR", details={"required_micro": 1})
        return {"txid": "tx_bonk", "height": 10, "fee": {}, "metadata": {}}

    node.setattr(token_fleet.meme, "create_token", create)
    report = token_fleet.run(majors=1, memes=1, dry_run=False)
    assert [entry["symbol"] for entry in report["created"]] == ["BONK"]
    assert report["failed"][0]["symbol"] == "BTC"
    assert report["failed"][0]["code"] == "INSUFFICIENT_FEE"
    assert report["failed"][0]["stage"] == "token"


