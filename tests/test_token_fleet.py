def test_plan_pairs_every_asset_with_its_own_wallet(node):
    plan = token_fleet.plan(majors=1, memes=1)
    assert plan["count"] == 2 and plan["to_mint"] == 2
    assert [row["wallet"] for row in plan["tokens"]] == ["fleet001", "fleet002"]
    assert [row["supply"] for row in plan["tokens"]] == [20_000_000, 88_000_000_000_000]
    assert plan["fee"]["tor_each"] == pricing.price("meme_token_create")
    assert plan["funding"]["tor_each"] == 6.0
    assert plan["estimated_tor"] == pytest.approx(2 * (6.0 + 0.1) + 2 * 5.0)
    assert plan["images"] == {"with_image": 2, "without_image": 0}
    assert plan["affordable"] is True


def test_a_dry_run_never_creates_a_wallet_or_mints(node):
    def explode(*args, **kwargs):
        raise AssertionError("a dry run must not touch the chain or the keystore")

    node.setattr(token_fleet.ledger, "new_wallet", explode)
    node.setattr(token_fleet.meme, "create_token", explode)
    report = token_fleet.run(majors=1, memes=1, dry_run=True)
    assert report["dry_run"] is True
    assert report["created"] == [] and report["failed"] == []
    assert report["to_mint"] == 2


def test_run_creates_a_wallet_funds_it_and_mints_the_feed_supply(make_wallet, minted):
    report = token_fleet.run(majors=1, memes=1, dry_run=False)
    assert report["created_count"] == 2 and report["failed"] == []
    by_symbol = {call["symbol"]: call for call in minted}
    assert by_symbol["BTC"]["supply"] == 20_000_000
    assert by_symbol["BONK"]["supply"] == 88_000_000_000_000
    assert by_symbol["BTC"]["image"] == "https://img.example/btc.png"
    assert by_symbol["BTC"]["wallet"] == "fleet001"
    entry = report["created"][0]
    assert entry["wallet"]["name"] == "fleet001"
    assert entry["wallet"]["address"].startswith("TOR1")
    assert entry["wallet"]["funding"]["funded"] is True
    assert entry["image"] == "https://img.example/btc.png"
    stored = json.loads(token_fleet._manifest_path().read_text(encoding="utf-8"))
    assert stored["count"] == 2 and stored["wallets"] == 2
    assert [row["symbol"] for row in stored["entries"]] == ["BTC", "BONK"]
    assert stored["totals"]["with_image"] == 2


